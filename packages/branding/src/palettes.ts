/**
 * Live preview color mapping used by the admin BrandingSection.
 * Matches the original PALETTE_COLORS record in BrandingSection.tsx.
 */
export const PALETTE_COLORS: Record<string, PalettePreviewColors> = Object.fromEntries(
  Object.entries(PALETTE_DEFINITIONS).map(([id, def]) => [
    id,
    {
      headerBg: def.header,
      sidebarBg: def.sidebar,
      contentBg: def.bg,
      success: def.success,
      danger: def.danger,
    },
  ]),
);

export function normalizeThemeId(themeId?: string | null): string {
  if (!themeId) return DEFAULT_THEME;
  const normalized = themeId.startsWith('palette-') ? themeId : `palette-${themeId}`;
  return PALETTE_DEFINITIONS[normalized] ? normalized : DEFAULT_THEME;
}

export function getPalette(themeId?: string | null): PaletteDefinition {
  const normalized = normalizeThemeId(themeId);
  return PALETTE_DEFINITIONS[normalized] || PALETTE_DEFINITIONS[DEFAULT_THEME];
}
