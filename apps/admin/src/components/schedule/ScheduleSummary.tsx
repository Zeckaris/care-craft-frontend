import {
  Alert,
  Card,
  Descriptions,
  Space,
  Statistic,
  Tag,
  Typography,
} from "antd";
import type { ISchedule, ScheduleStatus } from "@carecraft/types";
import { UnplacedLessonsTable } from "./UnplacedLessonsTable";
import { formatElapsedMs, formatSeed } from "./timetableUtils";

const { Text } = Typography;

interface ScheduleSummaryProps {
  schedule: ISchedule;
  /** Opens the drift report (used by the drifted-published warning). */
  onViewDrift?: () => void;
}

const STATUS_COLORS: Record<ScheduleStatus, string> = {
  draft: "blue",
  published: "green",
  archived: "default",
};

export function ScheduleSummary({
  schedule,
  onViewDrift,
}: ScheduleSummaryProps) {
  const stats = schedule.stats;

  return (
    <Space direction="vertical" size="middle" style={{ width: "100%" }}>
      <Card
        size="small"
        title={
          <Space>
            <span>Schedule summary</span>
            <Tag color={STATUS_COLORS[schedule.status] ?? "default"}>
              {schedule.status}
            </Tag>
            <Tag>v{schedule.version}</Tag>
          </Space>
        }
      >
        <Space size="large" wrap>
          <Statistic title="Placed lessons" value={schedule.entryCount} />
          <Statistic
            title="Unplaced lessons"
            value={schedule.stats?.unplacedCount ?? schedule.unplaced?.length ?? 0}
          />
          <Statistic title="Seed" value={formatSeed(stats?.seed)} />
          <Statistic
            title="Elapsed"
            value={formatElapsedMs(stats?.elapsedMs)}
          />
          <Statistic
            title="Time limit hit"
            value={stats?.timedOut ? "Yes" : "No"}
            valueStyle={stats?.timedOut ? { color: "#faad14" } : undefined}
          />
          <Statistic
            title="Hard violations"
            value={stats?.hardViolations ?? 0}
            valueStyle={
              (stats?.hardViolations ?? 0) > 0
                ? { color: "#cf1322" }
                : undefined
            }
          />
          <Statistic title="Soft score" value={stats?.softScore ?? 0} />
          <Statistic title="Restarts" value={stats?.restarts ?? 0} />
          <Statistic title="Iterations" value={stats?.iterations ?? 0} />
        </Space>
      </Card>

      {(stats?.hardViolations ?? 0) > 0 && (
        <Alert
          type="warning"
          showIcon
          message={`This schedule has ${stats.hardViolations} hard violation${
            stats.hardViolations === 1 ? "" : "s"
          }`}
          description="Hard constraints were broken. Review the schedule before relying on it."
        />
      )}

      {schedule.drifted === true && (
        <Alert
          type={schedule.status === "published" ? "warning" : "info"}
          showIcon
          message="This schedule has drifted"
          description={
            <span>
              Sections, assignments or settings changed after it was generated,
              so it may no longer reflect the current data.
              {schedule.status === "published" && (
                <>
                  {" "}
                  To correct it, create a draft from this schedule, fix the data
                  or regenerate, then publish.
                </>
              )}
            </span>
          }
          action={
            onViewDrift ? (
              <a onClick={onViewDrift}>View drift</a>
            ) : undefined
          }
        />
      )}

      <Card
        size="small"
        title={`Unplaced lessons (${schedule.unplaced?.length ?? 0})`}
      >
        {schedule.unplaced?.length ? (
          <UnplacedLessonsTable
            items={schedule.unplaced}
            schoolYear={schedule.schoolYear}
          />
        ) : (
          <Text type="secondary">
            Every lesson was placed. There are no unplaced lessons.
          </Text>
        )}
      </Card>

      <Card size="small" title="Generation details">
        <Descriptions size="small" column={2}>
          <Descriptions.Item label="Generated by">
            {schedule.generatedBy ?? "-"}
          </Descriptions.Item>
          <Descriptions.Item label="Generated at">
            {schedule.generatedAt
              ? new Date(schedule.generatedAt).toLocaleString()
              : "-"}
          </Descriptions.Item>
          <Descriptions.Item label="Fingerprint">
            {schedule.fingerprint || "-"}
          </Descriptions.Item>
          <Descriptions.Item label="Drift">
            {schedule.drifted === null
              ? "Unknown"
              : schedule.drifted
                ? "Drifted"
                : "In sync"}
          </Descriptions.Item>
          <Descriptions.Item label="Cloned from">
            {schedule.clonedFrom ?? "-"}
          </Descriptions.Item>
          <Descriptions.Item label="Published at">
            {schedule.publishedAt
              ? new Date(schedule.publishedAt).toLocaleString()
              : "-"}
          </Descriptions.Item>
        </Descriptions>
      </Card>
    </Space>
  );
}
